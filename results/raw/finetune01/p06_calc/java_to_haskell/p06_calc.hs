-- Parser for arithmetic expressions
expr :: Parser Int
expr = foldl1 (+) <$> many1 term
 
term :: Parser Int
term = foldl1 (*) <$> many1 factor
 
factor :: Parser Int
factor =
  negate <$ char '-' <*> expr
  <|> pure <$> expr
  <|> parens expr
 
parens :: Parser a -> Parser a
parens parser = between (char '(') (char ')') parser
 
-- Evaluate parsed expression
eval :: String -> Int
eval = fst . head . parse expr ""
 
