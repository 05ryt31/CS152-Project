"""Creates heatmap diagrams for aggregated data from a run.
Requires <run_id>_aggregate.csv to exist, generated by evals/aggregate.py.

Generates the following heatmaps, both per language pair and per paradigm pair:
- Average pass rate
- Average compile rate
- Average idiomaticity score
- Average heuristic count
- Average line of code difference
- Aggregate score, combining pass rate, idiomaticity score, and heuristic count

Usage (from repo root):
    python evals/figures.py --run-id base01
"""

import seaborn as sns
import matplotlib.pyplot as plt
import pandas as pd
import argparse
import csv
import sys
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PROBLEM_COUNT = 15
RUBRIC_MAX_SCORE = 12
HEURISTICS_REVERSE_WEIGHT = 100


def draw_heatmap(values: dict, title: str, run_dir: Path, heatmap_name: str, reverse_color: bool, show_int: bool):
    """
    Draws one cool/warm heatmap using the given values and title. The heatmap will be saved to run_dir with
    the given heatmap_name.
    """
    data = pd.Series(values).unstack()

    plt.figure(figsize=(8, 6))
    sns.heatmap(
        data, 
        annot=True,
        fmt=(".2f" if not show_int else ".0f"),
        cmap="coolwarm" + ("" if reverse_color else "_r"),
        linewidths=0.5
    )

    plt.title(title)
    plt.xlabel("To")
    plt.ylabel("From")
    plt.savefig(run_dir / f"{heatmap_name}.png")

def get_pair_count_per_paradigm(language_pairs: list, paradigm_pairs: list, paradigm_map: dict) -> dict:
    """
    Calculates the number of language pairs per paradigm pair.
    """
    result = {pair: 0 for pair in paradigm_pairs}
    for language_pair in language_pairs:
        if language_pair[0] != language_pair[1]:
            key = (paradigm_map[language_pair[0]], paradigm_map[language_pair[1]])
            result[key] += 1
    return result

def draw_heatmaps(run_dir: Path, run_id: str):
    """
    Draws twelve total heatmaps, for pass rate, compile rate, idiomaticity score, heuristic count,
    line of code difference, and aggregate score, per language pair and aggregate pair.

    The resulting heatmaps will be saved to the given `run_dir`.
    """
    with (
        open(run_dir / f"{run_id}_aggregate.csv", mode="r") as aggregate_csv,
        open(ROOT / "pipeline" / "matrix.json", mode="r") as matrix_data
    ):
        rows = csv.DictReader(aggregate_csv)
        matrix = json.load(matrix_data)

        PARADIGM_MAP = {k: v["family"] for k, v in matrix["languages"].items()}

        FIELDS = ["pass_rate", "compile_rate", "rubric_rate", "heuristics", "loc_diff", "aggregate"]
        LANGUAGE_PAIRS = list(itertools.product(PARADIGM_MAP.keys(), repeat=2))
        PARADIGM_PAIRS = list(set(itertools.product(PARADIGM_MAP.values(), repeat=2)))

        language_pair_stats = {}
        paradigm_stats = {}
        for field in FIELDS:
            language_pair_stats[field] = {pair: 0 for pair in LANGUAGE_PAIRS}
            paradigm_stats[field] = {pair: 0 for pair in PARADIGM_PAIRS}

        # Aggregate each language pair stat
        for row in rows:
            key = (row["src"], row["tgt"])
            language_pair_stats["pass_rate"][key] += float(row["pass_rate"])
            language_pair_stats["rubric_rate"][key] += float(row["rubric_score"])
            language_pair_stats["heuristics"][key] += int(row["heuristic_count"])
            language_pair_stats["compile_rate"][key] += 1 if (row["compiled"] == "True") else 0
            language_pair_stats["loc_diff"][key] += int(row["loc_diff"])

        for key in LANGUAGE_PAIRS:
            # Normalize each stat
            language_pair_stats["pass_rate"][key] /= PROBLEM_COUNT
            language_pair_stats["rubric_rate"][key] /= PROBLEM_COUNT * RUBRIC_MAX_SCORE
            language_pair_stats["compile_rate"][key] /= PROBLEM_COUNT
            language_pair_stats["loc_diff"][key] //= PROBLEM_COUNT
            language_pair_stats["heuristics"][key] //= PROBLEM_COUNT
            language_pair_stats["aggregate"][key] = language_pair_stats["pass_rate"][key] + language_pair_stats["rubric_rate"][key] - (language_pair_stats["heuristics"][key] / HEURISTICS_REVERSE_WEIGHT)

            # Calculate the paradigm stats
            paradigm_key = (PARADIGM_MAP[key[0]], PARADIGM_MAP[key[1]])
            paradigm_stats["pass_rate"][paradigm_key] += language_pair_stats["pass_rate"][key]
            paradigm_stats["rubric_rate"][paradigm_key] += language_pair_stats["rubric_rate"][key]
            paradigm_stats["compile_rate"][paradigm_key] += language_pair_stats["compile_rate"][key]
            paradigm_stats["heuristics"][paradigm_key] += language_pair_stats["heuristics"][key]
            paradigm_stats["loc_diff"][paradigm_key] += language_pair_stats["loc_diff"][key]

        # Strip out language pairs that are to and from the same language
        for field in FIELDS:
            language_pair_stats[field] = {k: v for k, v in language_pair_stats[field].items() if k[0] != k[1]}

        language_prefix = f"{run_id}_language_"
        draw_heatmap(language_pair_stats["pass_rate"], "Average Pass Rate per Language Pair", run_dir, f"{language_prefix}pass_rate", False, False)
        draw_heatmap(language_pair_stats["compile_rate"], "Average Compile Rate per Language Pair", run_dir, f"{language_prefix}compile_rate", False, False)
        draw_heatmap(language_pair_stats["rubric_rate"], "Average Idiomaticity Score per Language Pair", run_dir, f"{language_prefix}idiomaticity_score", False, False)
        draw_heatmap(language_pair_stats["heuristics"], "Average Heuristic Count per Language Pair", run_dir, f"{language_prefix}heuristic_count", True, True)
        draw_heatmap(language_pair_stats["loc_diff"], "Average Line of Code Difference per Language Pair", run_dir, f"{language_prefix}loc_diff", False, True)
        draw_heatmap(language_pair_stats["aggregate"], "Aggregate Score per Language Pair", run_dir, f"{language_prefix}aggregate_score", False, False)

        # Normalize the paradigm pairs
        counts = get_pair_count_per_paradigm(LANGUAGE_PAIRS, PARADIGM_PAIRS, PARADIGM_MAP)
        for key in PARADIGM_PAIRS:
            if not counts[key]:
                for field in FIELDS:
                    paradigm_stats[field].pop(key, None)
            else:
                paradigm_stats["pass_rate"][key] /= counts[key]
                paradigm_stats["rubric_rate"][key] /= counts[key]
                paradigm_stats["compile_rate"][key] /= counts[key]
                paradigm_stats["heuristics"][key] //= counts[key]
                paradigm_stats["loc_diff"][key] //= counts[key]
                paradigm_stats["aggregate"][key] += paradigm_stats["pass_rate"][key] + paradigm_stats["rubric_rate"][key] - (paradigm_stats["heuristics"][key] / HEURISTICS_REVERSE_WEIGHT)

        paradigm_prefix = f"{run_id}_paradigm_"
        draw_heatmap(paradigm_stats["pass_rate"], "Average Pass Rate per Paradigm Pair", run_dir, f"{paradigm_prefix}pass_rate", False, False)
        draw_heatmap(paradigm_stats["compile_rate"], "Average Compile Rate per Paradigm Pair", run_dir, f"{paradigm_prefix}compile_rate", False, False)
        draw_heatmap(paradigm_stats["rubric_rate"], "Average Idiomaticity Score per Paradigm Pair", run_dir, f"{paradigm_prefix}idiomaticity_score", False, False)
        draw_heatmap(paradigm_stats["heuristics"], "Average Heuristic Count per Paradigm Pair", run_dir, f"{paradigm_prefix}heuristic_count", True, True)
        draw_heatmap(paradigm_stats["loc_diff"], "Average Line of Code Difference per Paradigm Pair", run_dir, f"{paradigm_prefix}loc_diff", False, True)
        draw_heatmap(paradigm_stats["aggregate"], "Aggregate Score per Paradigm Pair", run_dir, f"{paradigm_prefix}aggregate_score", False, False)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--results-dir", type=Path,
                    help="folder with CSV files (default results/<run_id>_analysis)")
    args = ap.parse_args(argv)

    run_dir = args.results_dir or ROOT / "results" / f"{args.run_id}_analysis"
    if not run_dir.is_dir():
        raise SystemExit(f"no such run: {run_dir}")

    draw_heatmaps(run_dir, args.run_id)
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
